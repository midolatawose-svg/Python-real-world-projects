import turtle
turtle.Screen().colormode(255)
turtle.bgcolor(0,0,0)
pen = turtle.Turtle()
pen.color(255,255,0)
pen.pensize(5)
pen.penup()
pen.goto(-250,32)
pen.pendown()
pen.begin_fill()
for i in range(5):
    pen.forward(100)
    pen.right(144)
pen.end_fill()
pen.penup()
pen.goto(-60,0)
pen.pendown()
pen.color(135,206,250)
pen.begin_fill()
for i in range(5):
    pen.forward(350)
    pen.right(144)
pen.end_fill()
pen.penup()
pen.goto(250,-150)
pen.pendown()
pen.color(0,255,0)
pen.begin_fill()
for i in range(5):
    pen.forward(208)
    pen.right(144)
pen.end_fill()
pen.begin_fill
turtle.done()